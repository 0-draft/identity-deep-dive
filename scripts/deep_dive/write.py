#!/usr/bin/env python3
"""Write a staged deep dive from Claude's structured output, plus a PR body.

Usage:
  write.py --work deep-dive-work --result result.json --pr-body pr-body.md
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "scripts" / "insights"))
from guard import contains_secret  # noqa: E402
from tracks import TRACKS  # noqa: E402


def is_safe_slug(slug: str) -> bool:
    """A path segment that is also a valid git ref component."""
    return bool(
        SAFE_SLUG.fullmatch(slug) and ".." not in slug and not slug.endswith(".") and not slug.endswith(".lock")
    )
SAFE_SLUG = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,99}")
TEMPLATE = REPO_ROOT / "templates" / "deep-dive"
FILES = {
    "readme": "README.md",
    "context": "context.md",
    "spec_notes": "spec-notes.md",
    "interop_checklist": "interop-checklist.md",
}
# CommonMark fence: up to three spaces of indent; closed by the same character
# repeated at least as many times.
# A backtick fence's info string may not contain a backtick.
FENCE = re.compile(r"^ {0,3}(`{3,}(?!.*`)|~{3,})")
# An HTML tag start, but not an autolink like <https://...>.
TAG = re.compile(r"<(?!https?://)(?=[A-Za-z/!?])")
# Only a whole-line signature, so prose like "a nonce generated by the AS"
# stays.
SIGNATURE = re.compile(r"^\s*(\W\s*)?(generated (with|by) (claude|ai)\b|co-authored-by:)", re.IGNORECASE)
BARE_URL = re.compile(r"(?<![(<\[])\bhttps?://[^\s)>\]]+")
# Inline links may point at http(s), an anchor, or a relative Markdown file.
# The relative branch is anchored to the closing parenthesis, so "a.md:x" or
# "a.md.evil" do not slip through on the prefix.
UNSAFE_LINK = re.compile(r"\]\(\s*(?!https?://|#|(?:\.{1,2}/)?(?!/)[\w./-]+\.md(?:#[\w-]*)?\s*\))[^)]*\)")
# Headings of the templates in templates/deep-dive/, which the prompt asks
# the model to keep. Missing ones are listed in the PR body for the reviewer.
TEMPLATE_HEADINGS = {
    "README.md": (
        "## What this is",
        "## How it works",
        "## Use cases",
        "## Why This Matters Now",
        "## What Changed",
        "## Technical Analysis",
        "## Open Questions",
        "## Experiments",
        "## Sources",
    ),
    "context.md": ("# Context", "## Trigger", "## Why This Matters", "## Open Questions"),
    "spec-notes.md": ("# Spec Notes", "## References", "## Key Changes", "## Impact Analysis"),
    "interop-checklist.md": ("# Interop Checklist",),
}
# Reference definitions ("[1]: target") must point at http(s) too.
UNSAFE_REF = re.compile(r"^ {0,3}\[[^\]]+\]:\s*(?!https?://)")
# A code span is a run of N backticks closed by a run of exactly N.
CODE_SPAN = re.compile(r"(?<!`)(`+)(?!`)(.+?)(?<!`)\1(?!`)")


def _prose(segment: str) -> str:
    segment = TAG.sub("&lt;", segment)
    segment = UNSAFE_LINK.sub("]", segment)

    def wrap(m: re.Match[str]) -> str:
        url = m.group(0).rstrip(".,;:")
        return f"<{url}>{m.group(0)[len(url):]}"

    return BARE_URL.sub(wrap, segment)


def clean(markdown: str) -> str:
    """Escape inline HTML and drop unsafe links outside code."""
    out: list[str] = []
    fence: str | None = None
    for line in markdown.replace("\r\n", "\n").split("\n"):
        m = FENCE.match(line)
        if fence is None and m:
            fence = m.group(1)
            out.append(line.rstrip())
            continue
        if fence is not None:
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) and not line.strip()[len(m.group(1)):]:
                fence = None
            out.append(line.rstrip())
            continue
        if SIGNATURE.search(line) or UNSAFE_REF.match(line):
            continue
        # Code spans are left alone; everything between them is prose.
        pieces, pos = [], 0
        for span in CODE_SPAN.finditer(line):
            pieces.append(_prose(line[pos : span.start()]))
            pieces.append(span.group(0))
            pos = span.end()
        pieces.append(_prose(line[pos:]))
        out.append("".join(pieces).rstrip())
    text = "\n".join(out).strip()
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text + "\n"


SUBJECT_URL = re.compile(r"https://(datatracker\.ietf\.org/doc/[a-z0-9-]+/\d{2}/|github\.com/openid/[A-Za-z0-9._-]+)")
SUBJECT_NAME = re.compile(r"draft-[a-z0-9-]+|openid/[A-Za-z0-9._-]+")


def valid_subject(subject: dict) -> bool:
    """Every field of subject.json that reaches a path, git or the PR body."""
    track, slug = subject.get("track"), str(subject.get("slug", ""))
    rev = subject.get("rev")
    return (
        track in TRACKS
        and is_safe_slug(slug)
        and subject.get("branch") == f"deep-dive/{track}/{slug}"
        and bool(SUBJECT_NAME.fullmatch(str(subject.get("name", ""))))
        and bool(SUBJECT_URL.fullmatch(str(subject.get("url", ""))))
        and (rev is None or bool(re.fullmatch(r"\d{2}", str(rev))))
        and isinstance(subject.get("candidate", ""), str)
        and len(subject.get("candidate", "")) <= 300
        and "\n" not in subject.get("candidate", "")
    )


def no_mentions(text: str) -> str:
    """Keep "@name" in a PR body from notifying a real account."""
    return re.sub(r"(?<![\w.])@(?=[A-Za-z0-9])", "@\u200b", text)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", type=Path, required=True)
    ap.add_argument("--result", type=Path, required=True)
    ap.add_argument("--pr-body", type=Path, required=True)
    args = ap.parse_args()

    subject = json.loads((args.work / "subject.json").read_text(encoding="utf-8"))
    # subject.json crosses from the job that ran the model; check it again
    # before any of it becomes a path, a branch name or a git argument.
    if not valid_subject(subject):
        raise SystemExit("write: subject.json does not describe a valid subject")
    raw = args.result.read_text(encoding="utf-8").strip()
    if not raw:
        raise SystemExit("write: Claude returned no structured output")
    if contains_secret(raw):
        raise SystemExit("write: Claude output contains something shaped like a credential; refusing to publish it")
    result = json.loads(raw)
    for key in FILES:
        if not str(result.get(key, "")).strip():
            raise SystemExit(f"write: Claude output is missing {key}")

    target = REPO_ROOT / "tracks" / subject["track"] / "deep-dives" / subject["slug"]
    if target.exists():
        raise SystemExit(f"write: {target} already exists")
    target.mkdir(parents=True)
    for key, fname in FILES.items():
        (target / fname).write_text(clean(str(result[key])), encoding="utf-8")
    shutil.copy(TEMPLATE / "hands-on-log.md", target / "hands-on-log.md")

    one_liner = clean(str(result.get("one_liner", ""))).strip()
    unverified = [clean(str(u)).strip() for u in result.get("unverified", []) if str(u).strip()]
    rel = target.relative_to(REPO_ROOT)
    body = [
        f"Deep-dive draft for `{subject['name']}`{' revision ' + subject['rev'] if subject.get('rev') else ''} in `{subject['track']}`.",
        "",
        f"> {one_liner}",
        "",
        "## Why this subject",
        "",
        f"- Top candidate in `tracks/{subject['track']}/data/normalized/candidates.json` without a deep dive: `{subject['candidate'].replace('`', "'")}`",
    ]
    if subject.get("ai_note"):
        body.append(f"- Triage note: {clean(subject['ai_note']).strip()}")
    body += [
        "",
        "## Files",
        "",
        *[f"- `{rel}/{f}`" for f in [*FILES.values(), "hands-on-log.md"]],
        "",
        "`hands-on-log.md` is the empty template: experiments are for a person to run.",
        "",
        "## Sources",
        "",
        f"- {subject['url']}",
        "",
        "## Check before merging",
        "",
        "Drafted from the staged sources (the draft text or repository README, the latest revision diff, mailing-list messages, Datatracker states and earlier briefings from this repository). The model was told to use nothing else, but nothing enforces that: read it against the sources, fix what is wrong, and merge when it is something you would stand behind.",
        "",
    ]
    missing = [
        f"{fname}: `{h}`"
        for fname, headings in TEMPLATE_HEADINGS.items()
        for h in headings
        if h not in (target / fname).read_text(encoding="utf-8").splitlines()
    ]
    if missing:
        body += ["Template headings missing:", ""] + [f"- [ ] {m}" for m in missing] + [""]
    if unverified:
        body += ["Statements the drafter could not fully support from the material:", ""]
        body += [f"- [ ] {u}" for u in unverified] + [""]
    args.pr_body.write_text(no_mentions("\n".join(body)), encoding="utf-8")
    print(f"write: {rel} ({len(FILES) + 1} files), {len(unverified)} unverified statement(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
